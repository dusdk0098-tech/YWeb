import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
test("사진 보드: upload, circle highlight, rotate, undo/redo, save and PNG", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("이메일", { exact: true }).fill("test@example.test");
  await page.getByLabel("비밀번호", { exact: true }).fill("synthetic-e2e-password");
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: /오늘의 기록을/ })).toBeVisible();
  const s = await (await page.request.get("/api/session")).json();
  const site = await (await page.request.post("/api/sites", { headers: { Origin: "http://127.0.0.1:3107", "x-csrf-token": s.csrf, "idempotency-key": randomUUID() }, data: { name: "사진 보드 합성 " + randomUUID() } })).json();
  const pngBytes = Buffer.from(await page.evaluate(async () => {
    const c = document.createElement("canvas"); c.width = 40; c.height = 30;
    const g = c.getContext("2d")!; g.fillStyle = "#3a7"; g.fillRect(0, 0, 40, 30); g.fillStyle = "#c33"; g.fillRect(0, 0, 10, 10);
    const b = await new Promise<Blob>((done) => c.toBlob((x) => done(x!), "image/png"));
    return Array.from(new Uint8Array(await b.arrayBuffer()));
  }));
  await page.reload();
  await page.getByLabel("작업 현장").selectOption(site.id);
  await page.getByRole("button", { name: "사진 보드 ↗", exact: true }).click();
  await page.getByLabel("제목", { exact: true }).fill("작업 전후");
  await page.getByRole("button", { name: "사진 보드 만들기" }).click();
  await page.getByLabel("현장명").fill("합성 현장");
  await page.getByLabel("사진 추가(PNG·JPEG, 원본 보존)").setInputFiles({ name: "전.png", mimeType: "image/png", buffer: pngBytes });
  const preview = page.getByRole("img", { name: /1번 사진 전\.png 미리보기, 원형 강조 0개/ });
  await expect(preview).toBeVisible();
  await preview.click({ position: { x: 240, y: 180 } });
  await expect(page.getByRole("img", { name: /원형 강조 1개/ })).toBeVisible();
  await page.getByRole("img", { name: /원형 강조 1개/ }).press("Shift+ArrowLeft");
  await page.getByRole("button", { name: "90° 회전" }).click();
  await page.getByLabel("설명").fill("정리 완료");
  await page.getByRole("button", { name: "실행 취소" }).click();
  await expect(page.getByLabel("설명")).toHaveValue("");
  await page.getByRole("button", { name: "다시 실행" }).click();
  await expect(page.getByLabel("설명")).toHaveValue("정리 완료");
  await page.getByRole("button", { name: "사진 보드 저장" }).click();
  await expect(page.getByRole("status")).toHaveText("저장했습니다.");
  const board = (await (await page.request.get(`/api/sites/${site.id}/photo-boards`)).json()).items[0];
  const saved = await (await page.request.get(`/api/sites/${site.id}/photo-boards/${board.id}`)).json();
  expect(saved.scene.items[0].rotation).toBe(90);
  expect(saved.scene.items[0].circles).toHaveLength(1);
  expect(saved.scene.items[0].caption).toBe("정리 완료");
  expect(saved.body.siteName).toBe("합성 현장");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "PNG 저장" }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe("작업 전후.png");
  const bytes = await (await import("node:fs/promises")).readFile(await file.path());
  expect([...bytes.subarray(0, 4)]).toEqual([137, 80, 78, 71]);
});
