import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
test("TBM link participation: manager registers birth date, worker confirms without login", async ({ page, browser }) => {
  await page.goto("/");
  await page.getByLabel("이메일", { exact: true }).fill("test@example.test");
  await page.getByLabel("비밀번호", { exact: true }).fill("synthetic-e2e-password");
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: /오늘의 기록을/ })).toBeVisible();
  const s = await (await page.request.get("/api/session")).json(), headers = () => ({ Origin: "http://127.0.0.1:3107", "x-csrf-token": s.csrf, "idempotency-key": randomUUID() });
  const site = await (await page.request.post("/api/sites", { headers: headers(), data: { name: "참여 합성 " + randomUUID() } })).json();
  await page.request.post(`/api/sites/${site.id}/workers`, { headers: headers(), data: { name: "박참여", affiliation: "합성 소속", kind: "worker" } });
  await page.reload();
  await page.getByLabel("작업 현장").selectOption(site.id);
  await page.getByRole("button", { name: "명부 · 출역 ↗", exact: true }).click();
  await page.getByRole("button", { name: "근로자 · 방문자 명부", exact: true }).click();
  await page.getByLabel("생년월일(해시만 저장)").fill("1988-03-04");
  await page.getByRole("button", { name: "등록", exact: true }).click();
  await expect(page.getByText("참여 본인 확인: 생년월일 등록됨")).toBeVisible();
  await page.getByRole("button", { name: "TBM 기록 ↗", exact: true }).click();
  await page.getByRole("button", { name: "+ TBM 초안", exact: true }).click();
  await page.getByLabel("TBM 제목 *", { exact: true }).fill("참여 링크 TBM");
  await page.getByRole("button", { name: "TBM 초안 저장", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("서버에 저장됨");
  await page.getByRole("button", { name: /박참여 · 합성 소속/ }).click();
  await page.getByRole("button", { name: "참여 링크 만들기" }).click();
  const link = await page.getByLabel("참여 링크").inputValue();
  expect(link).toMatch(/\/join#t=[A-Za-z0-9_-]{43}$/);
  const qr = page.getByRole("img", { name: "참여 링크 QR 코드" });
  await expect(qr).toBeVisible();
  expect(await qr.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBe(240);
  const phone = await (await browser.newContext()).newPage(); // separate browser, not logged in
  await phone.goto(link);
  await expect(phone.getByText(/참여 링크 TBM/)).toBeVisible();
  await phone.getByLabel("이름").fill("박 참여");
  await phone.getByLabel("생년월일").fill("1988-03-05");
  await phone.getByRole("button", { name: "참여 기록" }).click();
  await expect(phone.getByRole("alert")).toContainText("맞지 않습니다");
  await phone.getByLabel("생년월일").fill("1988-03-04");
  await phone.getByRole("button", { name: "참여 기록" }).click();
  await expect(phone.getByRole("status")).toContainText("박참여님의 참여를 기록했습니다");
  await page.getByRole("button", { name: "참여 기록 새로 조회" }).click();
  await expect(page.getByText(/참여 기록 1건: 박참여/)).toBeVisible();
});
